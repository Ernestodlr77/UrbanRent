-- ================================================================
-- 1. TABLAS
-- Las tablas se crean primero SIN FOREIGN KEY.
-- Las relaciones se agregan al final, después de cargar los datos.
-- Esto evita problemas de orden durante la importación.
-- ================================================================

CREATE TABLE roles (
    id TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(80) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_roles_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE currencies (
    code CHAR(3) NOT NULL,
    name VARCHAR(100) NOT NULL,
    symbol VARCHAR(10) NULL,
    PRIMARY KEY (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE countries (
    code CHAR(3) NOT NULL,
    name VARCHAR(120) NOT NULL,
    englishName VARCHAR(120) NOT NULL,
    capital VARCHAR(120) NOT NULL,
    latitude DECIMAL(10,7) NOT NULL,
    longitude DECIMAL(10,7) NOT NULL,
    currencyCode CHAR(3) NOT NULL,
    PRIMARY KEY (code),
    KEY idx_countries_currency (currencyCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE property_types (
    code VARCHAR(20) NOT NULL,
    name VARCHAR(80) NOT NULL,
    PRIMARY KEY (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE users (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    fullName VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role ENUM('ADMIN','LANDLORD','TENANT') NOT NULL DEFAULT 'TENANT',
    phone VARCHAR(30) NULL,
    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_users_email (email),
    KEY idx_users_role (role)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE properties (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    landlordId BIGINT UNSIGNED NOT NULL,
    title VARCHAR(180) NOT NULL,
    description TEXT NULL,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(120) NOT NULL,
    countryCode CHAR(3) NOT NULL,
    countryName VARCHAR(120) NOT NULL,
    propertyType VARCHAR(20) NOT NULL DEFAULT 'APARTMENT',
    monthlyRent DECIMAL(12,2) NOT NULL,
    currencyCode CHAR(3) NOT NULL DEFAULT 'USD',
    latitude DECIMAL(10,7) NOT NULL,
    longitude DECIMAL(10,7) NOT NULL,
    status ENUM('AVAILABLE','RENTED','MAINTENANCE') NOT NULL DEFAULT 'AVAILABLE',
    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_properties_landlord (landlordId),
    KEY idx_properties_country (countryCode),
    KEY idx_properties_type (propertyType),
    KEY idx_properties_currency (currencyCode),
    KEY idx_properties_status (status),
    KEY idx_properties_city (city),
    CONSTRAINT chk_properties_rent CHECK (monthlyRent >= 0),
    CONSTRAINT chk_properties_lat CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_properties_lng CHECK (longitude BETWEEN -180 AND 180)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE contracts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    propertyId BIGINT UNSIGNED NOT NULL,
    tenantId BIGINT UNSIGNED NOT NULL,
    startDate DATE NOT NULL,
    endDate DATE NOT NULL,
    monthlyAmount DECIMAL(12,2) NOT NULL,
    depositAmount DECIMAL(12,2) NOT NULL DEFAULT 0,
    status ENUM('ACTIVE','COMPLETED','CANCELLED') NOT NULL DEFAULT 'ACTIVE',
    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_contracts_property (propertyId),
    KEY idx_contracts_tenant (tenantId),
    KEY idx_contracts_status (status),
    KEY idx_contracts_dates (startDate,endDate),
    CONSTRAINT chk_contract_dates CHECK (endDate > startDate),
    CONSTRAINT chk_contract_amounts CHECK (monthlyAmount >= 0 AND depositAmount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE payments (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    contractId BIGINT UNSIGNED NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    dueDate DATE NOT NULL,
    paidDate DATETIME NULL,
    status ENUM('PENDING','PAID','LATE') NOT NULL DEFAULT 'PENDING',
    notes VARCHAR(500) NULL,
    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_payments_contract (contractId),
    KEY idx_payments_status (status),
    KEY idx_payments_dueDate (dueDate),
    CONSTRAINT chk_payment_amount CHECK (amount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

