ALTER TABLE countries
    ADD CONSTRAINT fk_countries_currency
    FOREIGN KEY (currencyCode) REFERENCES currencies(code)
    ON UPDATE CASCADE ON DELETE RESTRICT;

ALTER TABLE properties
    ADD CONSTRAINT fk_properties_landlord
    FOREIGN KEY (landlordId) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT fk_properties_country
    FOREIGN KEY (countryCode) REFERENCES countries(code)
    ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT fk_properties_currency
    FOREIGN KEY (currencyCode) REFERENCES currencies(code)
    ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT fk_properties_type
    FOREIGN KEY (propertyType) REFERENCES property_types(code)
    ON UPDATE CASCADE ON DELETE RESTRICT;

ALTER TABLE contracts
    ADD CONSTRAINT fk_contracts_property
    FOREIGN KEY (propertyId) REFERENCES properties(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT fk_contracts_tenant
    FOREIGN KEY (tenantId) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE RESTRICT;

ALTER TABLE payments
    ADD CONSTRAINT fk_payments_contract
    FOREIGN KEY (contractId) REFERENCES contracts(id)
